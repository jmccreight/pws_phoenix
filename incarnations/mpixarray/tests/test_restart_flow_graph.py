"""Perfect-restart tests for the FlowGraph node types.

The R2 recipe (test_restart_processes.perfect_restart) applied to the
composed graph classes. Prognostic analysis of the seven node types
(flags live on the shared DataArrayMeta objects in each type's
``fields``, so every composition derives them):

- prms_channel: seg_inflow (advance_type reads the finalized daily
  mean -> inflow_ts_prev) + outflow_ts (the muskingum recursion
  crosses the day boundary) -- pywatershed's own channel restart list.
- starfit family: lake_storage_sub (the hourly marching storage) +
  lake_storage (the daily marching storage; also read by
  starfit_advance_type). lake_storage_old is REGENERATED by every
  advance; the accumulators are zeroed in prepare; the running means
  are recomputed within the day.
- starfit_daily adds lake_outflow_sub_next (computed at day end, read
  at the next day's first substep -- the one-day lag).
- pass_through / obsin / source_sink: NO prognostic state (their
  accumulators are zeroed in prepare; obsin's within-day latch never
  crosses the day boundary); the combined starfit_source_sink adds
  none beyond the family storages.

Coverage: the drb pure-channel graph (456 muskingum nodes) + the 115
STARFIT reference reservoirs in both reservoir modes (hourly
n_substeps=1 and daily n_substeps=24, the one-day-lag structure).
"""

