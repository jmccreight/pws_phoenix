INFLOW_FILE = STARFIT_DIR / "lake_inflow.nc"

DIS_FLOAT_VARS = ("seg_length", "seg_slope", "seg_depth")
S_PER_TIME = np.float64(60.0 * 60.0 * 24.0)

_drb_missing = [
    str(ff) for ff in pyws_domain_files("drb_2yr") if not ff.exists()
]
drb_skipif = pytest.mark.skipif(
    bool(_drb_missing),
    reason=(
        "pywatershed drb_2yr test data not generated; missing: "
        + ", ".join(_drb_missing[:3])
    ),
)

